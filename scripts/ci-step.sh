#!/usr/bin/env bash
# Запускает шаг CI и, если он упал, дублирует хвост вывода в аннотацию
# check-run. Лог job'а на GitHub скачивается только с админ-правами на
# репозиторий, поэтому без этого причина падения не видна ни в API, ни
# постороннему — а разбирать красный CI приходится именно по ней.
#
# Отдельный файл, а не inline в YAML: экранирование многострочного shell
# внутри YAML уже один раз дало синтаксически некорректный workflow.
#
#   bash scripts/ci-step.sh "Типы" npx tsc --noEmit
set -uo pipefail

name="$1"
shift

out=$("$@" 2>&1)
code=$?

printf '%s\n' "$out"

if [ "$code" -ne 0 ]; then
  # Аннотация обязана быть одной строкой: %0A — перевод строки внутри неё,
  # %25 — экранированный процент, иначе своё же %0A будет съедено
  msg=$(
    printf '%s\n' "$out" \
      | tail -n 40 \
      | sed -e 's/%/%25/g' -e 's/\r//g' \
      | awk '{printf "%s%%0A", $0}'
  )
  echo "::error title=${name}::${msg:-команда упала без вывода}"
fi

exit "$code"
