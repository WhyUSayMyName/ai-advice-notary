#!/usr/bin/env bash
# Установка зависимостей в CI с внятной диагностикой.
#
# Лог job'а на GitHub скачивается только с админ-правами на репозиторий,
# поэтому причина падения `npm ci` не видна ни в API, ни постороннему.
# Здесь хвост ошибки уходит ещё и в аннотацию check-run — она доступна всем.
# Скрипт вынесен из workflow намеренно: экранирование многострочного shell
# внутри YAML уже один раз дало синтаксически некорректный файл.
set -uo pipefail

if npm ci; then
  exit 0
fi
code=$?

# %0A — перевод строки в аннотации; сама аннотация обязана быть одной строкой
msg=$(
  cat "$HOME"/.npm/_logs/*.log 2>/dev/null \
    | grep -iE 'npm error|gyp ERR|ERR!' \
    | tail -n 30 \
    | sed -e 's/%/%25/g' -e 's/\r/ /g' \
    | awk '{printf "%s%%0A", $0}'
)

echo "::error title=npm ci::${msg:-нет строк с ошибкой в логе npm}"
exit "$code"
